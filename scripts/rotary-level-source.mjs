import * as defaultFs from 'node:fs/promises';

export function renderGeneratedLayout(layout) {
  const json = JSON.stringify(layout, null, 2);
  return '// Generated by scripts/rotary-level.mjs. Do not edit by hand.\n'
    + 'function deepFreeze(value) {\n'
    + "  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n"
    + '  Object.freeze(value);\n'
    + '  for (const child of Object.values(value)) deepFreeze(child);\n'
    + '  return value;\n'
    + '}\n\n'
    + `export const LEVEL18_ROTARY_LAYOUT = deepFreeze(${json});\n`;
}

export async function replaceFileSafely(target, content, fs = defaultFs) {
  const suffix = `${process.pid}-${Date.now()}`;
  const temporary = `${target}.tmp-${suffix}`;
  const backup = `${target}.bak-${suffix}`;
  await fs.writeFile(temporary, content, 'utf8');
  const current = await fs.readFile(target, 'utf8').catch(() => null);
  if (current === content) {
    await fs.rm(temporary, { force: true });
    return { changed: false };
  }
  if (current !== null) await fs.rename(target, backup);
  try {
    await fs.rename(temporary, target);
  } catch (error) {
    await fs.rm(temporary, { force: true });
    if (current !== null) await fs.rename(backup, target);
    throw error;
  }
  await fs.rm(backup, { force: true }).catch(() => undefined);
  return { changed: true };
}
